function createArticles(
  seeds: Seed[],
  sport: Sport,
  offset: number,
): Article[] {
  return seeds.map(
    (
      [
        title,
        englishTitle,
        summary,
        teamIds,
        playerIds,
        tags,
        demoHeat,
        illustrated,
      ],
      index,
    ) => ({
      id: `${sport}-${String(index + 1).padStart(2, "0")}`,
      title,
      englishTitle,
      summary,
      sport,
      sourceId: `demo-${sport}`,
      publishedAt: new Date(
        Date.parse(DEMO_NOW) - (index * 3 + offset) * 3600000,
      ).toISOString(),
      originalUrl: null,
      teamIds,
      playerIds,
      tags,
      demoHeat,
      isDemo: true,
      image: illustrated
        ? `images/${sport === "nba" ? "basketball" : sport === "football" ? "football" : "track"}.svg`
        : undefined,
      imageAlt: illustrated
        ? `SportNow 原创${sport === "nba" ? "篮球" : sport === "football" ? "足球" : "田径"}主题插画，非新闻现场照片`
        : undefined,
      paragraphs: [
        summary,
        `本篇以“${tags.find((t) => t === "战术" || t === "科普") || tags[0]}”为观察切口，使用原创的假设场景帮助展示阅读体验。我们希望在片段之外，留意站位、选择与配合之间的关系，给每一次观看留出思考的空间。`,
        "以上内容由 SportNow 为第一阶段前端演示原创编写，不是已发生事件的新闻报道，也不包含真实采访、伤病通报、交易确认或比赛结果。当前没有对应原文，因此不会提供虚构的媒体链接。后续接入经核验的新闻数据后，此处将展示有来源的中文摘要，并保留原文入口。",
      ],
      videos: [],
    }),
  );
}
